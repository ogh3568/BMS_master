"""Generate the SIL parameter table (bms_sil_params.c) from a cparams registry.

The generated file ``#include``s the model sources that hold the selected
parameters (unity build) so that file-scope ``static`` variables are reachable
without editing the user's code. Writable scalars, struct fields and array
elements are exposed by name through ``bms_sil_set_param``/``bms_sil_get_param``.

Not writable at run time (reported, not generated):
* ``#define`` constants -> rebuild with ``-DNAME=value`` (compile-time parameter),
* ``const`` objects -> writing them is undefined behaviour; make them writable in
  the SIL build only (e.g. a ``BMS_SIL`` build flag) after review.

CLI::

    python -m bmskit.sil.wrapgen registry.json -o build/bms_sil_params.c [--only name ...]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Iterable

C_TYPES = {
    "float": "F32", "double": "F64", "long double": "F64",
    "int": "I32", "signed int": "I32", "unsigned": "U32", "unsigned int": "U32",
    "short": "I16", "unsigned short": "U16", "char": "I8", "signed char": "I8", "unsigned char": "U8",
    "long": "I64", "unsigned long": "U64", "long long": "I64", "unsigned long long": "U64",
    "int8_t": "I8", "uint8_t": "U8", "int16_t": "I16", "uint16_t": "U16",
    "int32_t": "I32", "uint32_t": "U32", "int64_t": "I64", "uint64_t": "U64",
    "float32": "F32", "float64": "F64", "real32_T": "F32", "real64_T": "F64", "real_T": "F64",
}


def _base_type(ctype: str) -> str | None:
    t = re.sub(r"\b(const|static|volatile|extern)\b", "", ctype).strip()
    return C_TYPES.get(" ".join(t.split()))


def _elements(name: str, value, prefix: str = "") -> list[tuple[str, str]]:
    """(exposed name, C lvalue) for every element of a (nested) array."""
    out = []
    if isinstance(value, list):
        for i, v in enumerate(value):
            out += _elements(name, v, f"{prefix}[{i}]")
    else:
        out.append((f"{name}{prefix}", f"{name}{prefix}"))
    return out


def plan(registry: list[dict], only: set[str] | None = None,
         field_types: dict[str, str] | None = None) -> tuple[list[tuple[str, str, str]], list[dict], list[str]]:
    """Return (entries [(exposed, lvalue, typecode)], skipped [{name, reason}], source files)."""
    entries, skipped, files = [], [], []
    field_types = field_types or {}
    for r in registry:
        name, kind = r["name_in_code"], r["kind"]
        if only and name not in only and name.split("[")[0] not in only:
            continue
        if kind == "magic_number":
            continue
        if kind == "define":
            skipped.append({"name": name, "reason": "#define: compile-time, rebuild with -D override"})
            continue
        ctype = r.get("ctype", "")
        if "const" in ctype.split():
            skipped.append({"name": name, "reason": "const object: make writable in SIL build after review"})
            continue
        src_file = r["source"].split("#")[0]
        if kind == "struct_field":
            code = _base_type(field_types.get(name, ctype))
            if code is None:
                skipped.append({"name": name, "reason": f"unknown field type {ctype!r} (use --field-type)"})
                continue
            entries.append((name, name, code))
        elif kind == "array":
            code = _base_type(ctype)
            if code is None:
                skipped.append({"name": name, "reason": f"unsupported type {ctype!r}"})
                continue
            entries += [(n, lv, code) for n, lv in _elements(name, r["value"])]
        else:
            code = _base_type(ctype)
            if code is None:
                skipped.append({"name": name, "reason": f"unsupported type {ctype!r}"})
                continue
            entries.append((name, name, code))
        if src_file not in files:
            files.append(src_file)
    return entries, skipped, files


def render(entries, files: list[str], include_dirs_rel_to: Path | None = None) -> str:
    inc = []
    for f in files:
        path = Path(f)
        if include_dirs_rel_to is not None:
            try:
                path = Path(f).resolve().relative_to(include_dirs_rel_to.resolve())
            except ValueError:
                path = Path(f).resolve()
        inc.append(f'#include "{path.as_posix()}"')
    rows = "\n".join(f'    {{"{n}", (void *)&({lv}), BMS_{t}}},' for n, lv, t in entries)
    return f"""/* GENERATED by bmskit.sil.wrapgen - do not edit. Unity build: includes the model sources. */
#include <string.h>
#include <stdint.h>
#include "bms_sil_api.h"
{chr(10).join(inc)}

enum {{ BMS_F32, BMS_F64, BMS_I8, BMS_U8, BMS_I16, BMS_U16, BMS_I32, BMS_U32, BMS_I64, BMS_U64 }};
typedef struct {{ const char *name; void *ptr; int type; }} bms_sil_param_t;

static bms_sil_param_t g_bms_sil_params[] = {{
{rows}
    {{0, 0, 0}}
}};
#define BMS_SIL_N ((int)(sizeof(g_bms_sil_params) / sizeof(g_bms_sil_params[0])) - 1)

int bms_sil_api_version(void) {{ return BMS_SIL_API_VERSION; }}
int bms_sil_param_count(void) {{ return BMS_SIL_N; }}
const char *bms_sil_param_name(int idx) {{ return (idx >= 0 && idx < BMS_SIL_N) ? g_bms_sil_params[idx].name : 0; }}

static bms_sil_param_t *bms_sil_find(const char *name)
{{
    for (int i = 0; i < BMS_SIL_N; ++i)
        if (strcmp(g_bms_sil_params[i].name, name) == 0) return &g_bms_sil_params[i];
    return 0;
}}

int bms_sil_get_param(const char *name, double *value)
{{
    bms_sil_param_t *p = bms_sil_find(name);
    if (!p || !value) return -1;
    switch (p->type) {{
    case BMS_F32: *value = *(float *)p->ptr; break;
    case BMS_F64: *value = *(double *)p->ptr; break;
    case BMS_I8: *value = *(int8_t *)p->ptr; break;
    case BMS_U8: *value = *(uint8_t *)p->ptr; break;
    case BMS_I16: *value = *(int16_t *)p->ptr; break;
    case BMS_U16: *value = *(uint16_t *)p->ptr; break;
    case BMS_I32: *value = *(int32_t *)p->ptr; break;
    case BMS_U32: *value = *(uint32_t *)p->ptr; break;
    case BMS_I64: *value = (double)*(int64_t *)p->ptr; break;
    case BMS_U64: *value = (double)*(uint64_t *)p->ptr; break;
    default: return -1;
    }}
    return 0;
}}

int bms_sil_set_param(const char *name, double value)
{{
    bms_sil_param_t *p = bms_sil_find(name);
    if (!p) return -1;
    switch (p->type) {{
    case BMS_F32: *(float *)p->ptr = (float)value; break;
    case BMS_F64: *(double *)p->ptr = value; break;
    case BMS_I8: *(int8_t *)p->ptr = (int8_t)value; break;
    case BMS_U8: *(uint8_t *)p->ptr = (uint8_t)value; break;
    case BMS_I16: *(int16_t *)p->ptr = (int16_t)value; break;
    case BMS_U16: *(uint16_t *)p->ptr = (uint16_t)value; break;
    case BMS_I32: *(int32_t *)p->ptr = (int32_t)value; break;
    case BMS_U32: *(uint32_t *)p->ptr = (uint32_t)value; break;
    case BMS_I64: *(int64_t *)p->ptr = (int64_t)value; break;
    case BMS_U64: *(uint64_t *)p->ptr = (uint64_t)value; break;
    default: return -1;
    }}
    return 0;
}}
"""


def _cli(argv: Iterable[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m bmskit.sil.wrapgen")
    ap.add_argument("registry")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--only", nargs="*", help="limit to these parameter names")
    ap.add_argument("--field-type", action="append", default=[], metavar="NAME=CTYPE",
                    help="C type of a struct field, e.g. g_param.R0=float (default float)")
    args = ap.parse_args(list(argv) if argv is not None else None)
    reg = json.loads(Path(args.registry).read_text(encoding="utf-8"))
    ft = dict(x.split("=", 1) for x in args.field_type)
    entries, skipped, files = plan(reg, set(args.only) if args.only else None, ft)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(entries, files), encoding="utf-8")
    print(f"wrote {out}: {len(entries)} writable parameter(s)")
    for s in skipped:
        print(f"  skipped {s['name']}: {s['reason']}")
    return 0


if __name__ == "__main__":
    sys.exit(_cli())
